// node tools/lint.js [--write-docs]
// Static check of dist/app.js (the concatenated script):
//   * names declared twice at the shared top level (two files defining the same thing)
//   * identifiers that are used but declared nowhere (typos, things lost in a move)
// and, with --write-docs, regenerates docs/SYMBOLS.md: what every file defines and what it uses from other files.
const acorn = require('/opt/npm-tools/node_modules/acorn');
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(ROOT, 'dist/app.js'), 'utf8');
const BROWSER = new Set(('window document THREE Math performance requestAnimationFrame console Float32Array Uint16Array Uint32Array Uint8Array Object Array JSON Symbol ' +
  'setTimeout clearTimeout setInterval clearInterval parseFloat parseInt isNaN isFinite Number String Date Error undefined NaN Infinity navigator Promise arguments').split(' '));

let ast;
try { ast = acorn.parse(src, { ecmaVersion: 2020 }); } catch (e) { console.log('SYNTAX ERROR: ' + e.message); process.exit(1); }
const top = ast.body[0].expression.callee.body;              // body of the one enclosing function
// which file does a source position belong to?
const marks = []; const re = /\/\* =+ (\S+) =+ \*\//g; let m; while ((m = re.exec(src))) marks.push({ pos: m.index, file: m[1] });
const fileAt = p => { let f = '(build)'; for (const k of marks) if (k.pos <= p) f = k.file; else break; return f; };

function hoisted(fnBody) {                                    // var / function names declared directly in this function
  const names = [];
  (function w(n) {
    if (!n || typeof n.type !== 'string') return;
    if (n.type === 'FunctionDeclaration') { names.push(n.id); return; }
    if (n.type === 'FunctionExpression' || n.type === 'ArrowFunctionExpression') return;
    if (n.type === 'VariableDeclaration') n.declarations.forEach(d => { if (d.id.type === 'Identifier') names.push(d.id); });
    for (const k in n) { const v = n[k]; if (Array.isArray(v)) v.forEach(w); else if (v && typeof v.type === 'string') w(v); }
  })(fnBody);
  return names;
}
const topDecl = new Map(), dups = [];
hoisted(top).forEach(id => { const f = fileAt(id.start); if (topDecl.has(id.name) && topDecl.get(id.name) !== f) dups.push(id.name + '  (' + topDecl.get(id.name) + ' and ' + f + ')'); topDecl.set(id.name, f); });

const uses = new Map();                                       // top-level name -> Set(files that reference it)
const unknown = new Map();
function walk(n, scopes, parent, key) {
  if (!n || typeof n.type !== 'string') return;
  switch (n.type) {
    case 'FunctionDeclaration': case 'FunctionExpression': case 'ArrowFunctionExpression': {
      const s = new Set(n.params.map(p => p.name)); if (n.id && n.type === 'FunctionExpression') s.add(n.id.name);
      hoisted(n.body).forEach(id => s.add(id.name));
      walk(n.body, scopes.concat([s]), n, 'body'); return;
    }
    case 'CatchClause': walk(n.body, scopes.concat([new Set(n.param ? [n.param.name] : [])]), n, 'body'); return;
    case 'VariableDeclarator': walk(n.init, scopes, n, 'init'); return;
    case 'MemberExpression': walk(n.object, scopes, n, 'object'); if (n.computed) walk(n.property, scopes, n, 'property'); return;
    case 'Property': if (n.computed) walk(n.key, scopes, n, 'key'); walk(n.value, scopes, n, 'value'); return;
    case 'LabeledStatement': walk(n.body, scopes, n, 'body'); return;
    case 'BreakStatement': case 'ContinueStatement': return;
    case 'Identifier': {
      for (let i = scopes.length - 1; i >= 1; i--) if (scopes[i].has(n.name)) return;      // local
      if (topDecl.has(n.name)) { if (!uses.has(n.name)) uses.set(n.name, new Set()); uses.get(n.name).add(fileAt(n.start)); return; }
      if (!BROWSER.has(n.name)) { if (!unknown.has(n.name)) unknown.set(n.name, fileAt(n.start)); }
      return;
    }
  }
  for (const k in n) { if (k === 'type') continue; const v = n[k]; if (Array.isArray(v)) v.forEach(x => walk(x, scopes, n, k)); else if (v && typeof v.type === 'string') walk(v, scopes, n, k); }
}
walk(top, [new Set()], null, null);

let bad = false;
if (dups.length) { bad = true; console.log('DECLARED IN TWO FILES:\n  ' + dups.join('\n  ')); }
if (unknown.size) { bad = true; console.log('USED BUT NEVER DECLARED:\n  ' + [...unknown].map(([k, f]) => k + '  (first use in ' + f + ')').join('\n  ')); }
const unused = [...topDecl.keys()].filter(k => !uses.has(k));
if (unused.length) console.log('declared but never referenced: ' + unused.join(', '));
console.log((bad ? 'LINT FAILED' : 'lint ok') + ' - ' + topDecl.size + ' shared names in ' + marks.length + ' files');

if (process.argv.includes('--write-docs')) {
  const files = marks.map(k => k.file);
  let out = '# Symbol map (generated by `node tools/lint.js --write-docs` - do not edit)\n\nAll files in `src/js` share one function scope. This lists what each file defines there and what it takes from other files.\nA name in **bold** is used outside the file that defines it.\n';
  files.forEach(f => {
    const defs = [...topDecl].filter(([k, ff]) => ff === f).map(([k]) => k);
    const ext = {};
    uses.forEach((set, name) => { if (set.has(f) && topDecl.get(name) !== f) (ext[topDecl.get(name)] = ext[topDecl.get(name)] || []).push(name); });
    out += '\n## ' + f + '\n\n';
    out += 'Defines: ' + (defs.length ? defs.map(k => { const u = uses.get(k); return u && [...u].some(x => x !== f) ? '**' + k + '**' : k; }).join(', ') : '-') + '\n\n';
    const keys = Object.keys(ext).sort();
    out += 'Uses: ' + (keys.length ? keys.map(k => '`' + k + '`: ' + ext[k].sort().join(', ')).join('; ') : '-') + '\n';
  });
  fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'docs/SYMBOLS.md'), out);
  console.log('wrote docs/SYMBOLS.md');
}
process.exit(bad ? 1 : 0);
